-- ============================================================================================
-- V1: initial schema.
--
-- Flyway rules that are not negotiable:
--   * Versioned migrations are APPEND-ONLY. Once V1 has run anywhere, editing it changes its
--     checksum and every environment that already applied it refuses to start. Fix forward.
--   * One logical change per migration, small enough to review.
--   * Expand/contract for anything with downtime constraints: add a nullable column, backfill,
--     write to both, switch reads, then drop the old column in a LATER release.
--
-- Hibernate runs with ddl-auto=validate, so this file and the entities must agree exactly.
-- Types are chosen to be identical on H2 (MODE=PostgreSQL) and PostgreSQL.
-- ============================================================================================

create table orders (
    id              bigint generated by default as identity primary key,
    order_number    varchar(36)      not null,
    customer_email  varchar(255)     not null,
    status          varchar(32)      not null,
    total_amount    numeric(19, 2)   not null,
    currency        varchar(3)       not null,
    failure_reason  varchar(512),
    -- Optimistic locking. not null + default 0, so rows inserted by a script do not break the
    -- next UPDATE ... WHERE version = ?.
    version         bigint           not null default 0,
    created_at      timestamp(6) with time zone not null,
    updated_at      timestamp(6) with time zone not null,
    created_by      varchar(64),
    updated_by      varchar(64),
    -- A business key constraint, not just an index: this is what makes order placement
    -- idempotent at the database level.
    constraint uq_orders_order_number unique (order_number),
    -- Keep the database honest about the enum. The cost is a migration whenever the enum grows,
    -- which is a feature: adding a status IS a schema change.
    constraint ck_orders_status check (status in ('NEW', 'PAID', 'PAYMENT_FAILED', 'CANCELLED', 'SHIPPED')),
    constraint ck_orders_total check (total_amount >= 0)
);

create table order_line (
    id          bigint generated by default as identity primary key,
    order_id    bigint          not null,
    sku         varchar(64)     not null,
    quantity    integer         not null,
    unit_price  numeric(19, 2)  not null,
    constraint fk_order_line_order foreign key (order_id) references orders (id) on delete cascade,
    constraint ck_order_line_quantity check (quantity > 0)
);

create table stock_item (
    sku        varchar(64) primary key,
    available  integer not null,
    reserved   integer not null default 0,
    version    bigint  not null default 0,
    constraint ck_stock_available check (available >= 0),
    constraint ck_stock_reserved check (reserved >= 0)
);

create table payment_attempt (
    id                  bigint generated by default as identity primary key,
    order_number        varchar(36)     not null,
    amount              numeric(19, 2)  not null,
    attempt_no          integer         not null,
    result              varchar(16)     not null,
    provider_reference  varchar(64),
    detail              varchar(512),
    attempted_at        timestamp(6) with time zone not null,
    constraint ck_payment_result check (result in ('SUCCEEDED', 'DECLINED', 'ERROR'))
);

create table outbox_message (
    id              bigint generated by default as identity primary key,
    aggregate_type  varchar(64)   not null,
    aggregate_id    varchar(64)   not null,
    event_type      varchar(64)   not null,
    payload         varchar(4000) not null,
    created_at      timestamp(6) with time zone not null,
    published_at    timestamp(6) with time zone,
    attempts        integer       not null default 0
);

create table tx_note (
    id     bigint generated by default as identity primary key,
    label  varchar(128) not null
);
